-- (Maimoona Aziz 67070503473) Anvil Line Item
create table if not exists anvil_line_item(
  id bigint primary key generated by default as identity,
  created_at timestamp default now(),
  anvil_id bigint null references anvil(id) on delete restrict on update cascade, -- anvil id FK
  anvil_line_number bigint not null,
  target_tool_id bigint null references item(id) on delete restrict on update cascade, -- target tool FK
  current_durability bigint null, -- current durability
  sacrifice_item_id bigint null references item(id) on delete restrict on update cascade, -- sacrifice item id FK
  restored_durability bigint null, -- restored durability
  enchantment_id bigint null references enchantment(id) on delete restrict on update cascade -- enchantment id FK
);

