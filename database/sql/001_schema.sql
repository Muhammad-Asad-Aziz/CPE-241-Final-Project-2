    id SERIAL PRIMARY KEY,
    crafting_code text not null unique,
    crafting_date TIMESTAMP,
    session_id INTEGER, 
    player_id INTEGER REFERENCES player(id),
    target_item_id INTEGER REFERENCES item(id),
    qty_wanted INTEGER
